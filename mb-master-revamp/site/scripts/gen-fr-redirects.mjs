/**
 * Phase 1 of docs/FR-REBUILD-PLAN.md: no legacy French URL 404s at launch.
 *
 * Of the 74 legacy French URLs in redirects/content-map.json, 40 were
 * neither built nor redirected on 27 Sep 2026. This script writes a marked
 * block into public/.htaccess, next to the ones the sibling gen-*-redirects
 * scripts own, so each of them resolves. Redirects only: no French copy is
 * written or changed, which is why the owner released this phase ahead of
 * the EN lock (27 Sep 2026).
 *
 * Every rule points at the URL's final French destination from the plan.
 * Where that destination is not built yet, the rule points instead at the
 * closest live French page as a 302, because a temporary target must not
 * be cached as permanent by browsers or recorded as the page's new home by
 * search engines. Rerun this script after a planned page ships and its
 * rules turn into 301s (or disappear, for a page built at its own legacy
 * URL) on their own. No hand edits to the block.
 *
 * "Built" is read from the source, not from out/, so the script can run
 * before a build: a service is built when its group qualifies for FR in
 * content-map.json (lib/content-locale.ts's rule, `locale_actions`
 * included), a page when its route file exists under app/fr/.
 *
 * Rules stay inside the locale (content-map `_rules`): a French URL never
 * redirects to an English page.
 *
 *   node scripts/gen-fr-redirects.mjs
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const SITE = fileURLToPath(new URL("../", import.meta.url));
const MAP = join(SITE, "../redirects/content-map.json");
const HTACCESS = join(SITE, "public/.htaccess");

const BEGIN = "# BEGIN fr-safety-net (generated by site/scripts/gen-fr-redirects.mjs)";
const END = "# END fr-safety-net";

// The main French page (owner, 27 Sep 2026) and the interim target of last
// resort while the French homepage and indexes are unbuilt.
const FR_MAIN = "fr/services/seo/";

/**
 * EN parent service -> its French page, per docs/FR-REBUILD-PLAN.md.
 * `planned` pages do not exist yet; `interim` is where their URLs point
 * until they do.
 */
const FR_PARENT = {
  "multilingual-seo": { slug: "referencement-multilingue" },
  "website-localisation": { slug: "localisation-de-site-web" },
  "translation-services": { slug: "traduction-professionnelle", interim: "fr/services/localisation-juridique-reglementaire/" },
  "app-and-software-localisation": { slug: "localisation-applications", interim: "fr/services/localisation-de-site-web/" },
  "multilingual-content": { slug: "creation-de-contenu-multilingue", interim: "fr/services/referencement-multilingue/" },
  "ai-consulting": { slug: "conseil-ia", interim: FR_MAIN },
  "ai-translation-and-post-editing": { slug: "postedition-ia", interim: "fr/services/localisation-de-site-web/" },
  "technical-seo": { slug: "seo-technique", interim: FR_MAIN },
};

/**
 * Legacy French pages -> final destination, and the route file that builds
 * that destination. The two Globaprom service URLs go to the homepage
 * (owner decision 6).
 */
const FR_PAGE_TARGET = {
  "page-accueil": { to: "fr/", route: "app/fr/page.tsx" },
  "404-2": { to: "fr/", route: "app/fr/page.tsx" },
  "nos-services": { to: "fr/services/", route: "app/fr/services/page.tsx" },
  "notre-equipe": { to: "fr/notre-equipe/", route: "app/fr/notre-equipe/page.tsx" },
  "nous-contacter": { to: "fr/nous-contacter/", route: "app/fr/nous-contacter/page.tsx" },
  "tarifs": { to: "fr/tarifs/", route: "app/fr/tarifs/page.tsx" },
  "blog": { to: "fr/blog/", route: "app/fr/blog/page.tsx" },
  "conception-de-site-web": { to: "fr/", route: "app/fr/page.tsx" },
  "marketing-digital": { to: "fr/", route: "app/fr/page.tsx" },
};

const cm = JSON.parse(readFileSync(MAP, "utf8"));
const actionFor = (g) => g.locale_actions?.fr ?? g.action;
const builtServices = new Set(
  cm.groups
    .filter((g) => g.type === "service" && actionFor(g) === "migrate" && g.destination === "mdx" && g.fr)
    .map((g) => g.fr.slug)
);
const serviceBuilt = (slug) => builtServices.has(slug);
const routeBuilt = (route) => existsSync(join(SITE, route));
const pathOf = (url) => url.replace(/^https?:\/\/[^/]+\//, "");

const rules = []; // { from, to, code, note }
const unresolved = [];

for (const g of cm.groups) {
  if (!g.fr?.url) continue;
  const from = pathOf(g.fr.url);
  const action = actionFor(g);

  // Posts and services already built at their URL, and the Valencia
  // exodus (gen-redirects.mjs), need nothing here.
  if (action === "migrate" && g.type !== "page") continue;
  if (action === "relocate" && g.destination === "valenciamove") continue;

  if (g.type === "page" || (action === "relocate" && g.destination === "globaprom")) {
    const t = FR_PAGE_TARGET[g.fr.slug];
    if (!t) { unresolved.push(from); continue; }
    if (t.to === from && routeBuilt(t.route)) continue; // built at its own URL
    if (routeBuilt(t.route)) rules.push({ from, to: t.to, code: 301 });
    else rules.push({ from, to: FR_MAIN, code: 302, note: `until /${t.to} ships` });
    continue;
  }

  if (action === "absorb") {
    const p = FR_PARENT[g.absorbed_into];
    if (!p) { unresolved.push(from); continue; }
    const to = `fr/services/${p.slug}/`;
    if (to === from && serviceBuilt(p.slug)) continue;
    if (serviceBuilt(p.slug)) rules.push({ from, to, code: 301 });
    else rules.push({ from, to: p.interim, code: 302, note: `until /${to} ships` });
    continue;
  }

  unresolved.push(from);
}

// The planned indexes are not legacy URLs, but a French reader trimming a
// URL back to /fr/services/ should not 404 either.
if (!routeBuilt("app/fr/services/page.tsx")) {
  rules.push({ from: "fr/services/", to: FR_MAIN, code: 302, note: "until /fr/services/ ships" });
}

if (unresolved.length) {
  console.error(`no French destination known for:\n  ${unresolved.join("\n  ")}\nAdd it to FR_PARENT or FR_PAGE_TARGET.`);
  process.exit(1);
}

rules.sort((a, b) => a.from.localeCompare(b.from));
const esc = (p) => p.replace(/\/$/, "");
const lines = [
  BEGIN,
  "# Do not hand-edit this block. Edit docs/FR-REBUILD-PLAN.md's targets in",
  "# this script and regenerate with `node scripts/gen-fr-redirects.mjs`.",
  `# ${rules.length} legacy French URLs: ${rules.filter((r) => r.code === 301).length} permanent, ` +
    `${rules.filter((r) => r.code === 302).length} temporary (302) until their French page ships.`,
  "<IfModule mod_rewrite.c>",
  "RewriteEngine On",
  ...rules.map((r) => `RewriteRule ^${esc(r.from)}/?$ ${r.to} [R=${r.code},L]${r.note ? `\n# ^ ${r.note}` : ""}`),
  "</IfModule>",
  END,
];
const block = lines.join("\n");

let ht = readFileSync(HTACCESS, "utf8");
const re = new RegExp(`${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END}`);
ht = re.test(ht) ? ht.replace(re, block) : `${ht.replace(/\n*$/, "")}\n\n${block}\n`;
writeFileSync(HTACCESS, ht);
console.log(`fr-safety-net: ${rules.length} rules written to public/.htaccess`);
