/**
 * Inject the Apache/LiteSpeed rules for the Valencia exodus into
 * public/.htaccess, between marker comments.
 *
 * Not next.config.js. CLAUDE.md says redirects are generated into
 * `next.config.js redirects()`, and that cannot work here: the site is
 * `output: "export"`, and a static export has no server to run a redirect
 * in. Next drops `redirects()` silently in export mode, so following the
 * documented route would have produced a config that looked right, built
 * green, and served 404s on every legacy URL.
 *
 * Not a separate exodus.htaccess file either, which is what this script
 * did until it was caught: it wrote a real .htaccess with real rules,
 * FTP-Deploy-Action shipped it to the server, and Apache never read it.
 * A directory's rewrite rules live in the one file named exactly
 * `.htaccess`; a second file with rules in it sits next to that file and
 * does nothing unless something explicitly includes it. Nothing did.
 * Every redirect this generator ever wrote has been inert since the
 * first run. Injecting into the real .htaccess, in a marked block this
 * script owns and everything else in the file is left untouched, is
 * what actually serves a 301.
 *
 * Only `exact` and `merge` records emit a rule. A `new` record has no
 * target yet, and a redirect to a page that does not exist is worse than
 * no redirect: it turns a 404 into a 301 to a 404, which is harder to
 * find and hides the missing page from the crawl report.
 */
import { readFileSync, writeFileSync } from "fs";

const MAP = new URL("../../redirects/valencia-exodus.json", import.meta.url).pathname;
const HTACCESS = new URL("../public/.htaccess", import.meta.url).pathname;

const BEGIN = "# BEGIN valencia-exodus (generated by site/scripts/gen-redirects.mjs)";
const END = "# END valencia-exodus";

const map = JSON.parse(readFileSync(MAP, "utf8"));
const ready = map.records.filter((r) => r.to);
const pending = map.records.filter((r) => !r.to);

const block = [
  BEGIN,
  "# Do not hand-edit this block. Edit redirects/valencia-exodus.json and",
  "# regenerate with `node scripts/gen-redirects.mjs`.",
  `# ${ready.length} of ${map.records.length} URLs have a target; ${pending.length} are waiting on a page`,
  "# to exist on valenciamove.com.",
  "<IfModule mod_rewrite.c>",
  "RewriteEngine On",
  ...ready.flatMap((r) => {
    const from = r.from.replace(/^\/|\/$/g, "");
    const lines = r.note ? [`# ${r.note}`] : [];
    lines.push(`RewriteRule ^${from}/?$ ${map.target_host}${r.to} [R=301,L]`);
    return lines;
  }),
  "</IfModule>",
  END,
].join("\n");

const current = readFileSync(HTACCESS, "utf8");
const beginIdx = current.indexOf(BEGIN);
const endIdx = current.indexOf(END);

let next;
if (beginIdx !== -1 && endIdx !== -1) {
  next = current.slice(0, beginIdx) + block + current.slice(endIdx + END.length);
} else {
  const sep = current.endsWith("\n") ? "\n" : "\n\n";
  next = current + sep + block + "\n";
}

if (!process.argv.includes("--dry")) writeFileSync(HTACCESS, next);

console.log(`${ready.length} rules written into public/.htaccess`);
console.log(`${pending.length} URLs still have no target on valenciamove.com:`);
for (const r of pending) console.log(`  ${r.from}`);
