/**
 * Emit the Apache/LiteSpeed rules for the Valencia exodus.
 *
 * Not next.config.js. CLAUDE.md says redirects are generated into
 * `next.config.js redirects()`, and that cannot work here: the site is
 * `output: "export"`, and a static export has no server to run a redirect
 * in. Next drops `redirects()` silently in export mode, so following the
 * documented route would have produced a config that looked right, built
 * green, and served 404s on every legacy URL. The host is Hostinger,
 * which is LiteSpeed and reads .htaccess, so the rules go there.
 *
 * Only `exact` and `merge` records emit a rule. A `new` record has no
 * target yet, and a redirect to a page that does not exist is worse than
 * no redirect: it turns a 404 into a 301 to a 404, which is harder to
 * find and hides the missing page from the crawl report.
 */
import { readFileSync, writeFileSync } from "fs";

const MAP = new URL("../../redirects/valencia-exodus.json", import.meta.url).pathname;
const OUT = new URL("../public/exodus.htaccess", import.meta.url).pathname;

const map = JSON.parse(readFileSync(MAP, "utf8"));
const ready = map.records.filter((r) => r.to);
const pending = map.records.filter((r) => !r.to);

const lines = [
  "# Valencia exodus: mikebastin.com -> valenciamove.com",
  "# Generated by site/scripts/gen-redirects.mjs from redirects/valencia-exodus.json.",
  "# Do not hand-edit. Edit the JSON and regenerate.",
  `# ${ready.length} of ${map.records.length} URLs have a target; ${pending.length} are waiting on a page`,
  "# to exist on valenciamove.com.",
  "",
  "<IfModule mod_rewrite.c>",
  "RewriteEngine On",
];
for (const r of ready) {
  const from = r.from.replace(/^\/|\/$/g, "");
  if (r.note) lines.push(`# ${r.note}`);
  lines.push(`RewriteRule ^${from}/?$ ${map.target_host}${r.to} [R=301,L]`);
}
lines.push("</IfModule>", "");

if (!process.argv.includes("--dry")) writeFileSync(OUT, lines.join("\n"));

console.log(`${ready.length} rules written to public/exodus.htaccess`);
console.log(`${pending.length} URLs still have no target on valenciamove.com:`);
for (const r of pending) console.log(`  ${r.from}`);
