/**
 * Inject the 301s from a live blog post's legacy bare-slug URL
 * (mikebastin.com/<slug>/, no /blog/ prefix -- how WordPress served every
 * post) to its new /blog/<slug>/ home, into public/.htaccess.
 *
 * Same reasoning and same mechanism as gen-redirects.mjs and
 * gen-prune-redirects.mjs: this is a static export, next.config.js
 * redirects() never runs on the server, and a second .htaccess-shaped
 * file next to the real one is inert unless something includes it. The
 * real .htaccess, in a marked block this script owns, is what actually
 * serves a 301.
 *
 * Source of truth is redirects/content-map.json: every group with
 * `type: "post"`, `action: "migrate"`, `destination: "mdx"` and an `en`
 * entry gets a rule, except the one whose EN slug already has a
 * hand-built page at that exact bare-slug route
 * (competitor-analysis-traffic-checklist, see lib/posts.ts) -- that one
 * already 200s at its legacy URL, so a rule for it would redirect a page
 * to itself.
 *
 * EN only. FR and ES qualifying posts exist in content-map.json too (18
 * and 20 respectively) but have no /blog/ template yet -- see the PR
 * description for the follow-up.
 */
import { readFileSync, writeFileSync } from "fs";

const MAP = new URL("../../redirects/content-map.json", import.meta.url).pathname;
const HTACCESS = new URL("../public/.htaccess", import.meta.url).pathname;

const BEGIN = "# BEGIN blog-posts (generated by site/scripts/gen-blog-redirects.mjs)";
const END = "# END blog-posts";

// Kept in sync with lib/posts.ts's HAND_BUILT_SLUGS by hand -- both files
// read the same content-map.json, but this one has no reason to import
// TypeScript, so the one slug it needs to skip is repeated here rather
// than shared.
const HAND_BUILT_SLUGS = ["competitor-analysis-traffic-checklist"];

const cm = JSON.parse(readFileSync(MAP, "utf8"));
const slugs = cm.groups
  .filter(
    (g) =>
      g.type === "post" &&
      g.action === "migrate" &&
      g.destination === "mdx" &&
      g.en &&
      !HAND_BUILT_SLUGS.includes(g.en.slug)
  )
  .map((g) => g.en.slug)
  .sort();

const block = [
  BEGIN,
  "# Do not hand-edit this block. Edit redirects/content-map.json and",
  "# regenerate with `node scripts/gen-blog-redirects.mjs`.",
  `# ${slugs.length} EN posts, legacy bare-slug URL -> /blog/<slug>/.`,
  `# ${HAND_BUILT_SLUGS.join(", ")} excluded: hand-built page already lives at`,
  "# the bare-slug route, so a rule for it would redirect a page to itself.",
  "<IfModule mod_rewrite.c>",
  "RewriteEngine On",
  ...slugs.map((slug) => `RewriteRule ^${slug}/?$ blog/${slug}/ [R=301,L]`),
  "</IfModule>",
  END,
].join("\n");

const current = readFileSync(HTACCESS, "utf8");
const beginIdx = current.indexOf(BEGIN);
const endIdx = current.indexOf(END);

let next;
if (beginIdx !== -1 && endIdx !== -1) {
  next = current.slice(0, beginIdx) + block + current.slice(endIdx + END.length);
} else {
  const sep = current.endsWith("\n") ? "\n" : "\n\n";
  next = current + sep + block + "\n";
}

if (!process.argv.includes("--dry")) writeFileSync(HTACCESS, next);

console.log(`${slugs.length} rules written into public/.htaccess`);
