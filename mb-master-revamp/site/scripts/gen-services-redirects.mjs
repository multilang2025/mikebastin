/**
 * Inject the 301s for the 43-to-19 services consolidation
 * (docs/CONTENT-ARCHITECTURE.md section 3) into public/.htaccess, in their
 * own marked block next to the Valencia exodus, blog-posts and
 * blog-prune-audit ones the sibling generators own. Same reasoning as
 * those scripts: this is a static export, next.config.js redirects()
 * never runs on the server, and a second .htaccess-shaped file next to the
 * real one is never read by Apache unless something includes it, which
 * nothing does.
 *
 * Source of truth is redirects/content-map.json: every `type: "service"`
 * group with `action: "absorb"` gets a same-site 301 from its legacy
 * `/services/<slug>/` to `/services/<absorbed_into>/`, read straight off
 * the group (no hardcoded target map, unlike gen-prune-redirects.mjs,
 * because `absorbed_into` already names the target for every absorb
 * group here).
 *
 * The two `action: "relocate"` groups (web-design, digital-marketing) are
 * the one place this script does NOT do what a first read of the task
 * suggests. content-map.json carries no target URL for either
 * (`vm_target_url` is Valencia-exodus-only and is null on both) --
 * `destination: "globaprom"` only says which network property the topic
 * belongs to, not a page to 301 onto. docs/CONTENT-ARCHITECTURE.md section
 * 3 resolves it explicitly: "301 both to /services/multilingual-seo/ and
 * carry a contextual network link to globaprom.com per the linking policy
 * in HANDOFF.md §19." HANDOFF.md §19 is itself a same-page contextual-link
 * rule (in-sentence, dofollow, never bolded), not a page-relocation rule --
 * Globaprom does not have a page that replaces either of these, and
 * shipping a 301 to a third-party domain nobody read first is exactly the
 * mistake gen-redirects.mjs's own header comment warns about. So both
 * relocate groups get the same same-site target as every absorb group,
 * multilingual-seo, and the Globaprom link itself belongs in that page's
 * copy, not in this script.
 *
 * The 10 in-place legacy slugs (`action: "migrate"`, same EN slug before
 * and after) need no rule -- they already resolve -- and are listed below
 * only as a sanity-check comment so a future run of this script visibly
 * accounts for all 43 EN legacy service URLs, not just the 33 it redirects.
 */
import { readFileSync, writeFileSync } from "fs";

const MAP = new URL("../../redirects/content-map.json", import.meta.url).pathname;
const HTACCESS = new URL("../public/.htaccess", import.meta.url).pathname;

const BEGIN = "# BEGIN services-consolidation (generated by site/scripts/gen-services-redirects.mjs)";
const END = "# END services-consolidation";

// Sanity-check only, not used to generate rules. The 10 legacy EN service
// slugs that were reused exactly as the consolidated page's slug, per
// content-map.json's `action: "migrate"` service groups with an `en`
// entry. They already 200 at their legacy URL, so a rule for one of them
// would redirect a page to itself.
const IN_PLACE_SLUGS = [
  "spanish-seo", "multilingual-seo", "multilingual-sem", "german-seo", "french-seo",
  "italian-seo", "local-seo", "dutch-seo", "portuguese-seo", "website-localisation",
];

const RELOCATE_TARGET = "multilingual-seo";

const cm = JSON.parse(readFileSync(MAP, "utf8"));
const serviceGroups = cm.groups.filter((g) => g.type === "service");

const absorb = serviceGroups.filter((g) => g.action === "absorb" && g.en);
const relocate = serviceGroups.filter((g) => g.action === "relocate" && g.en);
const migrate = serviceGroups.filter((g) => g.action === "migrate" && g.en);

for (const g of absorb) {
  if (!g.absorbed_into) throw new Error(`"${g.en.slug}" is action:absorb with no absorbed_into target`);
}

const missingInPlace = migrate.map((g) => g.en.slug).filter((s) => !IN_PLACE_SLUGS.includes(s));
if (missingInPlace.length) {
  throw new Error(
    `migrate service group(s) not in IN_PLACE_SLUGS, add or explain: ${missingInPlace.join(", ")}`
  );
}

const rows = [
  ...absorb.map((g) => ({ slug: g.en.slug, target: g.absorbed_into, note: null })),
  ...relocate.map((g) => ({
    slug: g.en.slug,
    target: RELOCATE_TARGET,
    note:
      "relocate/globaprom: content-map.json has no target URL for this group; CONTENT-ARCHITECTURE.md " +
      "section 3 resolves it to a same-site 301 here plus a contextual network link to globaprom.com " +
      "inside the target page's copy (HANDOFF.md section 19), not a 301 off-site.",
  })),
].sort((a, b) => a.slug.localeCompare(b.slug));

const block = [
  BEGIN,
  "# Do not hand-edit this block. Edit redirects/content-map.json (absorbed_into",
  "# per group) and regenerate with `node scripts/gen-services-redirects.mjs`.",
  `# ${rows.length} legacy /services/<slug>/ URLs consolidated: ${absorb.length} absorbed`,
  `# same-site, ${relocate.length} relocate-to-globaprom topics redirected same-site per`,
  "# CONTENT-ARCHITECTURE.md section 3 (see this file's header comment). The other",
  `# ${IN_PLACE_SLUGS.length} legacy service slugs kept their exact URL and need no rule.`,
  "<IfModule mod_rewrite.c>",
  "RewriteEngine On",
  ...rows.flatMap((r) => {
    const lines = r.note ? [`# ${r.note}`] : [];
    lines.push(`RewriteRule ^services/${r.slug}/?$ services/${r.target}/ [R=301,L]`);
    return lines;
  }),
  "</IfModule>",
  END,
].join("\n");

const current = readFileSync(HTACCESS, "utf8");
const beginIdx = current.indexOf(BEGIN);
const endIdx = current.indexOf(END);

let next;
if (beginIdx !== -1 && endIdx !== -1) {
  next = current.slice(0, beginIdx) + block + current.slice(endIdx + END.length);
} else {
  const sep = current.endsWith("\n") ? "\n" : "\n\n";
  next = current + sep + block + "\n";
}

if (!process.argv.includes("--dry")) writeFileSync(HTACCESS, next);

console.log(`${rows.length} rules written into public/.htaccess`);
for (const r of rows) console.log(`  ${r.slug.padEnd(45)} -> /services/${r.target}/`);
