/**
 * Inject the 301s for top-level page reframes into public/.htaccess, in
 * their own marked block next to the Valencia exodus, blog-posts,
 * blog-prune-audit and services-consolidation blocks the sibling
 * generators own. Same reasoning as those scripts: this is a static
 * export, next.config.js redirects() never runs on the server, and a
 * second .htaccess-shaped file next to the real one is never read by
 * Apache unless something includes it, which nothing does.
 *
 * Source of truth is redirects/content-map.json: every `type: "page"`
 * group with `action: "reposition"` gets a rule from its legacy EN slug
 * to its current EN slug, read straight off the group (the slug itself
 * was updated in place to the new destination when the page was
 * repositioned, e.g. g048 pricing -> how-i-work).
 *
 * `migrate` page groups (about-us, contact-us, our-services, homepage,
 * blog, 404-2) are not covered here yet: about-us, our-services and a
 * dedicated 404 page have no built route on the new site to redirect to,
 * and a redirect to a page that does not exist is worse than no redirect
 * (see gen-redirects.mjs's header comment). contact-us -> /contact/ does
 * have a live target but is a separate gap from the one this script was
 * written to close; add it here, or to its own generator, in a pass that
 * reads and signs off on the rest of the `page` type groups rather than
 * folding it in as a drive-by.
 */
import { readFileSync, writeFileSync } from "fs";

const MAP = new URL("../../redirects/content-map.json", import.meta.url).pathname;
const HTACCESS = new URL("../public/.htaccess", import.meta.url).pathname;

const BEGIN = "# BEGIN page-reposition (generated by site/scripts/gen-page-redirects.mjs)";
const END = "# END page-reposition";

const cm = JSON.parse(readFileSync(MAP, "utf8"));

// Legacy EN slug per group, keyed by group id, since content-map.json's
// `en.slug` was updated in place to the new destination slug and no
// longer carries the legacy one this rule needs to redirect from.
const LEGACY_EN_SLUG = { g048: "pricing" };

/**
 * Legacy pages with no page of their own on the new site, pointed at the
 * page that now does their job.
 *
 * Found on 20 Sep by resolving docs/sitemap-MB-EN.txt against the built
 * output and the generated rules: five URLs of record had neither a page
 * nor a redirect, so they would have 404ed on launch, against the rule in
 * CLAUDE.md that says none of them may. Four are marked `migrate` to
 * `mdx` in content-map.json and have content files, but no route was ever
 * written to render them, so they fell through the build and through
 * every generator. The fifth was never in the content map at all.
 *
 * They are listed here rather than given routes because none of them
 * needs to exist as a page: the new site answers all four questions
 * somewhere else. /contact-us/ and /about-us/ are also the two most
 * linked-to targets in the whole harvested corpus, 23 and 18 links.
 */
const RETIRED_PAGES = [
  { from: "contact-us", to: "contact", why: "/contact/ is the live contact page" },
  { from: "about-us", to: "how-i-work", why: "no about page; how-i-work carries the same ground" },
  { from: "our-services", to: "services", why: "the services index replaced it" },
  { from: "404-2", to: "", why: "a stray WordPress 404 page, sent to the homepage" },
  {
    from: "how-to-use-twitter-for-beginners",
    to: "blog",
    why: "never harvested, no content file and no successor. 1,522 impressions at position 70, so the hub is the honest target rather than a page that does not cover it",
  },
];

const rows = [
  ...cm.groups
    .filter((g) => g.type === "page" && g.action === "reposition" && g.en)
    .map((g) => {
      const legacy = LEGACY_EN_SLUG[g.group];
      if (!legacy) throw new Error(`no legacy EN slug recorded for reposition group "${g.group}", add it to LEGACY_EN_SLUG`);
      return { group: g.group, from: legacy, to: g.en.slug };
    }),
  ...RETIRED_PAGES.map((r) => ({ group: "retired-page", from: r.from, to: r.to, why: r.why })),
].sort((a, b) => a.from.localeCompare(b.from));

const block = [
  BEGIN,
  "# Do not hand-edit this block. Edit redirects/content-map.json (the group's",
  "# en.slug) and this file's own LEGACY_EN_SLUG map, then regenerate with",
  "# `node scripts/gen-page-redirects.mjs`.",
  `# ${rows.length} top-level page(s) reframed under a new slug.`,
  "<IfModule mod_rewrite.c>",
  "RewriteEngine On",
  ...rows.map((r) => `RewriteRule ^${r.from}/?$ ${r.to}/ [R=301,L]`),
  "</IfModule>",
  END,
].join("\n");

const current = readFileSync(HTACCESS, "utf8");
const beginIdx = current.indexOf(BEGIN);
const endIdx = current.indexOf(END);

let next;
if (beginIdx !== -1 && endIdx !== -1) {
  next = current.slice(0, beginIdx) + block + current.slice(endIdx + END.length);
} else {
  const sep = current.endsWith("\n") ? "\n" : "\n\n";
  next = current + sep + block + "\n";
}

if (!process.argv.includes("--dry")) writeFileSync(HTACCESS, next);

console.log(`${rows.length} rules written into public/.htaccess`);
for (const r of rows) console.log(`  ${r.from} -> ${r.to}/`);
