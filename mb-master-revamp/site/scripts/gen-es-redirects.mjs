/**
 * The Spanish twin of gen-fr-redirects.mjs (docs/ES-REBUILD-PLAN.md,
 * phase 1): no legacy Spanish URL 404s at launch.
 *
 * Of the 70 legacy Spanish URLs in redirects/content-map.json, 40 were
 * neither built nor redirected on 30 Sep 2026: 6 pages, the pricing page,
 * 31 absorbed services and 2 Globaprom services. This script writes a
 * marked block into public/.htaccess, next to the ones the sibling
 * gen-*-redirects scripts own, so each of them resolves.
 *
 * Every rule points at the URL's final Spanish destination from the plan.
 * Where that destination is not built yet, the rule points at the closest
 * live Spanish page as a 302, because a temporary target must not be
 * cached as permanent by browsers or recorded as the page's new home by
 * search engines. Rerun the script after a planned page ships and its
 * rules turn into 301s (or disappear, for a page built at its own legacy
 * URL) on their own. No hand edits to the block.
 *
 * "Built" is read from the source, not from out/, so the script can run
 * before a build: a service is built when its group qualifies for ES in
 * content-map.json (lib/content-locale.ts's rule, `locale_actions`
 * included), a page when its route file exists under app/es/.
 *
 * Rules stay inside the locale (content-map `_rules`): a Spanish URL never
 * redirects to an English page.
 *
 *   node scripts/gen-es-redirects.mjs
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const SITE = fileURLToPath(new URL("../", import.meta.url));
const MAP = join(SITE, "../redirects/content-map.json");
const HTACCESS = join(SITE, "public/.htaccess");

const BEGIN = "# BEGIN es-safety-net (generated by site/scripts/gen-es-redirects.mjs)";
const END = "# END es-safety-net";

// The main Spanish page (SEO for a Spanish exporter) and the interim
// target of last resort while the Spanish homepage and indexes are unbuilt.
const ES_MAIN = "es/services/optimizacion-seo/";

/**
 * EN parent service -> its Spanish page, per docs/ES-REBUILD-PLAN.md.
 * `interim` is where a URL points until the page exists.
 */
const ES_PARENT = {
  "multilingual-seo": { slug: "posicionamiento-multilingue" },
  "website-localisation": { slug: "traduccion-de-paginas-web" },
  "translation-services": { slug: "traduccion-profesional", interim: "es/services/traduccion-de-paginas-web/" },
  "app-and-software-localisation": { slug: "localizacion-de-aplicaciones", interim: "es/services/traduccion-de-paginas-web/" },
  "multilingual-content": { slug: "redaccion-seo-multilingue", interim: "es/services/posicionamiento-multilingue/" },
  "ai-consulting": { slug: "consultoria-de-inteligencia-artificial", interim: ES_MAIN },
  "ai-translation-and-post-editing": { slug: "posedicion-de-ia", interim: "es/services/traduccion-de-paginas-web/" },
  "technical-seo": { slug: "seo-tecnico", interim: ES_MAIN },
};

/**
 * Legacy Spanish pages -> final destination, and the route file that builds
 * that destination. The two Globaprom service URLs go to the homepage, as
 * in French (owner decision 6).
 */
const ES_PAGE_TARGET = {
  "es": { to: "es/", route: "app/es/page.tsx" },
  "404-2": { to: "es/", route: "app/es/page.tsx" },
  "blog": { to: "es/blog/", route: "app/es/blog/page.tsx" },
  "contactanos": { to: "es/contactanos/", route: "app/es/contactanos/page.tsx" },
  "conocenos-agencia-experta-en-seo": { to: "es/conocenos-agencia-experta-en-seo/", route: "app/es/conocenos-agencia-experta-en-seo/page.tsx" },
  "precios": { to: "es/precios/", route: "app/es/precios/page.tsx" },
  "servicios-consultoria-web": { to: "es/services/", route: "app/es/services/page.tsx" },
  "diseno-web": { to: "es/", route: "app/es/page.tsx" },
  "marketing-digital-valencia": { to: "es/", route: "app/es/page.tsx" },
};

const cm = JSON.parse(readFileSync(MAP, "utf8"));
const actionFor = (g) => g.locale_actions?.es ?? g.action;
const builtServices = new Set(
  cm.groups
    .filter((g) => g.type === "service" && actionFor(g) === "migrate" && g.destination === "mdx" && g.es)
    .map((g) => g.es.slug)
);
const serviceBuilt = (slug) => builtServices.has(slug);
const routeBuilt = (route) => existsSync(join(SITE, route));
const pathOf = (url) => url.replace(/^https?:\/\/[^/]+\//, "");

const rules = []; // { from, to, code, note }
const unresolved = [];

for (const g of cm.groups) {
  if (!g.es?.url) continue;
  const from = pathOf(g.es.url);
  const action = actionFor(g);

  // Posts and services already built at their URL, and the Valencia
  // exodus (gen-redirects.mjs), need nothing here.
  if (action === "migrate" && g.type !== "page") continue;
  if (action === "relocate" && g.destination === "valenciamove") continue;

  if (g.type === "page" || (action === "relocate" && g.destination === "globaprom")) {
    const t = ES_PAGE_TARGET[g.es.slug];
    if (!t) { unresolved.push(from); continue; }
    if (t.to === from && routeBuilt(t.route)) continue; // built at its own URL
    if (routeBuilt(t.route)) rules.push({ from, to: t.to, code: 301 });
    // Once the Spanish homepage exists it is the natural stand-in for an
    // unbuilt page; before that, the main Spanish service page was.
    else rules.push({ from, to: routeBuilt("app/es/page.tsx") ? "es/" : ES_MAIN, code: 302, note: `until /${t.to} ships` });
    continue;
  }

  if (action === "absorb") {
    const p = ES_PARENT[g.absorbed_into];
    if (!p) { unresolved.push(from); continue; }
    const to = `es/services/${p.slug}/`;
    if (to === from && serviceBuilt(p.slug)) continue;
    if (serviceBuilt(p.slug)) rules.push({ from, to, code: 301 });
    else rules.push({ from, to: p.interim, code: 302, note: `until /${to} ships` });
    continue;
  }

  unresolved.push(from);
}

// The planned indexes are not legacy URLs, but a Spanish reader trimming a
// URL back to /es/services/ should not 404 either.
if (!routeBuilt("app/es/services/page.tsx")) {
  rules.push({ from: "es/services/", to: ES_MAIN, code: 302, note: "until /es/services/ ships" });
}

if (unresolved.length) {
  console.error(`no Spanish destination known for:\n  ${unresolved.join("\n  ")}\nAdd it to ES_PARENT or ES_PAGE_TARGET.`);
  process.exit(1);
}

rules.sort((a, b) => a.from.localeCompare(b.from));
const esc = (p) => p.replace(/\/$/, "");
const lines = [
  BEGIN,
  "# Do not hand-edit this block. Edit docs/ES-REBUILD-PLAN.md's targets in",
  "# this script and regenerate with `node scripts/gen-es-redirects.mjs`.",
  `# ${rules.length} legacy Spanish URLs: ${rules.filter((r) => r.code === 301).length} permanent, ` +
    `${rules.filter((r) => r.code === 302).length} temporary (302) until their Spanish page ships.`,
  "<IfModule mod_rewrite.c>",
  "RewriteEngine On",
  ...rules.map((r) => `RewriteRule ^${esc(r.from)}/?$ ${r.to} [R=${r.code},L]${r.note ? `\n# ^ ${r.note}` : ""}`),
  "</IfModule>",
  END,
];
const block = lines.join("\n");

let ht = readFileSync(HTACCESS, "utf8");
const re = new RegExp(`${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END}`);
ht = re.test(ht) ? ht.replace(re, block) : `${ht.replace(/\n*$/, "")}\n\n${block}\n`;
writeFileSync(HTACCESS, ht);
console.log(`es-safety-net: ${rules.length} rules written to public/.htaccess`);
