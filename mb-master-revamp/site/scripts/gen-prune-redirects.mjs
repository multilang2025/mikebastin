/**
 * Inject the 301s for the blog prune audit (docs/BLOG-PRUNE-AUDIT.md) into
 * public/.htaccess, in their own marked block next to the Valencia exodus
 * one gen-redirects.mjs owns. Same reasoning as that script: a static
 * export has no server for next.config.js redirects() to run in, and a
 * second .htaccess-shaped file next to the real one is never read by
 * Apache unless something includes it, which nothing does. Learned that
 * the hard way once already; not repeating it here.
 *
 * Source of truth is redirects/content-map.json's `action`/`destination`
 * fields (retire or absorb, destination "prune"), not the audit doc's
 * prose -- the doc can drift, the map is what content-migrator and any
 * future pass actually reads. TARGETS below is this script's own record
 * of where each one goes, since content-map.json's `absorbed_into` field
 * only names a slug for MERGE, not a full path, and REMOVE has no field
 * for it at all.
 *
 * One rule worth keeping visible: no redirect chains. boosting-local-seo's
 * natural merge target is optimise-a-google-business-profile, but that
 * post is itself retiring in the same batch, so it points straight at
 * that post's own final destination rather than a 301 to a page that is
 * about to stop existing. That destination changed once already: both
 * posts first pointed at /services/technical-seo/, because that is where
 * local-seo lived before the owner corrected it on 6 Sep (off-site/local
 * visibility work is not technical-seo's subject). Both now point at
 * /services/local-seo/, the page that correction created.
 */
import { readFileSync, writeFileSync } from "fs";

const MAP = new URL("../../redirects/content-map.json", import.meta.url).pathname;
const HTACCESS = new URL("../public/.htaccess", import.meta.url).pathname;

const BEGIN = "# BEGIN blog-prune-audit (generated by site/scripts/gen-prune-redirects.mjs)";
const END = "# END blog-prune-audit";

const TARGETS = {
  "language-service-providers": ["/services/", "Vendor-comparison/competitor-promotion content with no owning service; the services index is the honest hub rather than a false single match."],
  "affordable-seo-services": ["/services/", "Pricing overlap spans several consolidated services, not one; the services index is the honest hub."],
  "seo-mistakes-to-avoid": ["/blog/", "Generic listicle, no unique angle, no page it naturally belongs under."],
  "roi-of-website-localisation": ["/services/website-localisation/", "The website-localisation service page already makes this case, with an offer behind it."],
  "cultural-differences-in-multilingual-websites": ["/services/multilingual-content/", "Topic is already the multilingual-content service's job."],
  "language-data-analysis": ["/blog/", "Vague premise, not tied to AI or marketing despite the slug; no page it naturally belongs under."],
  "optimise-a-google-business-profile": ["/services/local-seo/", "Owner correction 6 Sep: this is off-site/local visibility work, not technical-seo. local-seo has its own page now."],
  "how-to-make-money-on-youtube": ["/blog/", "Owner confirmed 6 Sep: no experience in that space, nothing on the site to point it at."],
  "boosting-local-seo": ["/services/local-seo/", "Owner correction 6 Sep: this is off-site SEO, not technical-seo. Same cluster as optimise-a-google-business-profile, which is retiring to the same page in this batch -- pointed directly here rather than chaining through a post that is about to disappear."],
  "long-tail-keywords": ["/blog/multilingual-keyword-research/", "multilingual-keyword-research already owns this topic, with 2,852 impressions, and stays live at its Journal URL now that /blog/ is wired up."],
};

const cm = JSON.parse(readFileSync(MAP, "utf8"));
const rows = cm.groups
  .filter((r) => (r.action === "retire" || r.action === "absorb") && r.destination === "prune" && r.en)
  .map((r) => {
    const slug = r.en.slug;
    const t = TARGETS[slug];
    if (!t) throw new Error(`no redirect target assigned for "${slug}" -- add it to TARGETS`);
    return { slug, action: r.action, target: t[0], note: t[1] };
  })
  .sort((a, b) => a.slug.localeCompare(b.slug));

const block = [
  BEGIN,
  "# Do not hand-edit this block. Targets live in this script's own TARGETS",
  "# map (not content-map.json, which only names a slug for MERGE); update",
  "# there and regenerate with `node scripts/gen-prune-redirects.mjs`.",
  `# ${rows.length} posts retired from the blog prune audit: ${rows.filter((r) => r.action === "retire").length} REMOVE, ${rows.filter((r) => r.action === "absorb").length} MERGE.`,
  "<IfModule mod_rewrite.c>",
  "RewriteEngine On",
  ...rows.flatMap((r) => [`# ${r.note}`, `RewriteRule ^${r.slug}/?$ ${r.target.replace(/^\//, "")} [R=301,L]`]),
  "</IfModule>",
  END,
].join("\n");

const current = readFileSync(HTACCESS, "utf8");
const beginIdx = current.indexOf(BEGIN);
const endIdx = current.indexOf(END);

let next;
if (beginIdx !== -1 && endIdx !== -1) {
  next = current.slice(0, beginIdx) + block + current.slice(endIdx + END.length);
} else {
  const sep = current.endsWith("\n") ? "\n" : "\n\n";
  next = current + sep + block + "\n";
}

if (!process.argv.includes("--dry")) writeFileSync(HTACCESS, next);

console.log(`${rows.length} rules written into public/.htaccess`);
for (const r of rows) console.log(`  ${r.action.padEnd(7)} ${r.slug.padEnd(55)} -> ${r.target}`);
