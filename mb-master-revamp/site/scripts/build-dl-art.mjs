#!/usr/bin/env node
/**
 * Rebuilds lib/dl-art-data.ts and app/dl-art.css from the archive in
 * design/dl-art/ (owner, 30 Sep 2026: illustrations recycled from the
 * rejected Delaguía y Luzón design proposal, reused as drawn and recoloured
 * to this site's tokens). The archive keeps all 25 illustrations as
 * extracted; only the ones listed in USED ship.
 *
 * The animations are the originals (CSS modules class names kept, so two
 * illustrations never collide). Colour goes through `--d3-*` and `--art-*`
 * variables, which `.dl-art` maps to this site's band tokens, so the plate,
 * lines and the one accent follow Night Swell and Morning Glass.
 *
 *   node scripts/build-dl-art.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const ARCHIVE = join(ROOT, "..", "design", "dl-art");

// `convergence-world`, `convergence-europe`, `globe-world` and `globe-europe`
// are the same drawings on a world or a Europe map (design/dl-art/geo); they
// share the CSS of their base illustration.
const USED = [
  "convergence", "convergence-world", "convergence-europe", "globe", "globe-world", "globe-europe",
  "constellation", "audit", "hexagons", "gears", "orbits", "puzzle", "venn", "amphora",
  "roundtable", "clock", "skyline",
];

const VARS = `/* Generated by scripts/build-dl-art.mjs from design/dl-art. Do not edit. */
.dl-art {
  --d3-bg2: color-mix(in srgb, var(--bg) 90%, var(--ink));
  --d3-border: var(--rule);
  --d3-line: var(--dim);
  --d3-muted: var(--dim);
  --d3-text: var(--ink);
  --d3-head: var(--ink);
  --d3-brass: var(--berry);
}
`;

const data = {};
let css = VARS;
const cssDone = new Set();
for (const key of USED) {
  const html = readFileSync(join(ARCHIVE, `${key}.svg.html`), "utf8");
  const cls = html.match(/wrapper class: (\S+)/)[1];
  const svg = html.slice(html.indexOf("<svg")).trim();
  data[key] = { cls, svg };
  const base = key.replace(/-(world|europe)$/, "");
  if (!cssDone.has(base)) {
    cssDone.add(base);
    css += readFileSync(join(ARCHIVE, `${base}.css`), "utf8");
  }
}

writeFileSync(
  join(ROOT, "lib", "dl-art-data.ts"),
  `// Generated by scripts/build-dl-art.mjs from design/dl-art. Do not edit.\nexport const DL_ART: Record<string, { cls: string; svg: string }> = ${JSON.stringify(data, null, 1)};\n`
);
writeFileSync(join(ROOT, "app", "dl-art.css"), css);
console.log(`wrote ${USED.length} illustrations, ${(css.length / 1024).toFixed(0)} KB of CSS`);
